"""
FaceEmbedding ORM model.

Stores face embeddings (512-dimensional vectors) for enrolled students.
Each student can have multiple embeddings from different capture angles
for improved recognition accuracy.
"""

import uuid
from datetime import datetime, timezone
from typing import TYPE_CHECKING
from uuid import UUID

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, String, UUID as SQL_UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.student import Student

# pgvector column type — imported conditionally to allow testing without pgvector
try:
    from pgvector.sqlalchemy import Vector
except ImportError:
    # Fallback for environments without pgvector installed
    from sqlalchemy import LargeBinary as Vector  # type: ignore[assignment]


class FaceEmbedding(Base):
    """
    Stored face embedding for a registered student.

    Each embedding is a 512-dimensional float vector generated by the
    face recognition model (ArcFace/AdaFace). Multiple embeddings per
    student improve recognition robustness across poses and lighting.

    Attributes:
        id: Primary key.
        student_id: The student this embedding belongs to.
        embedding: 512-d face embedding vector (pgvector).
        image_path: Path to the source face image (encrypted at rest).
        quality_score: Quality score of the source image at enrollment time.
        capture_angle: Capture angle description (front, left, right, etc.).
        is_active: Whether this embedding is used for recognition.
        created_at: Record creation timestamp.
    """

    __tablename__ = "face_embeddings"

    id: Mapped[UUID] = mapped_column(SQL_UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    student_id: Mapped[UUID] = mapped_column(
        ForeignKey("students.id", ondelete="CASCADE"), nullable=False, index=True
    )
    embedding = mapped_column(Vector(512), nullable=False)
    image_path: Mapped[str | None] = mapped_column(String(500), nullable=True)
    quality_score: Mapped[float | None] = mapped_column(Float, nullable=True)
    capture_angle: Mapped[str | None] = mapped_column(String(20), nullable=True)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc)
    )

    # Relationships
    student: Mapped["Student"] = relationship(back_populates="face_embeddings")  # noqa: F821

    def __repr__(self) -> str:
        return (
            f"<FaceEmbedding(id={self.id}, student_id={self.student_id}, "
            f"angle='{self.capture_angle}', active={self.is_active})>"
        )
